-- Run this once in Supabase SQL Editor for JLaw's student_scores table.
-- Student submissions are anonymous inserts. Only users whose app_metadata.role
-- is "admin" can read submitted rows through the Data API.

create table if not exists public.student_scores (
  id bigint generated by default as identity primary key,
  student_name text not null,
  score integer not null,
  total_questions integer not null,
  time_taken_seconds integer not null,
  responses jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.student_scores
  add column if not exists responses jsonb not null default '[]'::jsonb,
  add column if not exists created_at timestamptz not null default now();

alter table public.student_scores enable row level security;

revoke all on table public.student_scores from anon, authenticated;
grant insert on table public.student_scores to anon;
grant select on table public.student_scores to authenticated;

drop policy if exists "JLaw anonymous score submissions" on public.student_scores;
create policy "JLaw anonymous score submissions"
on public.student_scores
for insert
to anon
with check (
  char_length(student_name) > 0
  and score >= 0
  and total_questions > 0
  and score <= total_questions
  and time_taken_seconds >= 0
  and jsonb_typeof(responses) = 'array'
);

drop policy if exists "JLaw admins can view submissions" on public.student_scores;
create policy "JLaw admins can view submissions"
on public.student_scores
for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Needed by anon submissions when id is generated by an identity/serial sequence.
do $$
declare
  score_sequence regclass := pg_get_serial_sequence('public.student_scores', 'id');
begin
  if score_sequence is not null then
    execute format('grant usage, select on sequence %s to anon', score_sequence);
  end if;
end
$$;
