-- Run once in Supabase SQL Editor. Students authenticate with Supabase Auth.
-- Grant app_metadata.role = 'admin' only to trusted Admin accounts.

create table if not exists public.quiz_sets (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  minutes integer not null default 20 check (minutes between 1 and 600),
  questions jsonb not null default '[]'::jsonb,
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.student_scores (
  id bigint generated by default as identity primary key,
  student_name text not null,
  score integer not null default 0,
  total_questions integer not null default 0,
  time_taken_seconds integer not null default 0,
  responses jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  student_id uuid references auth.users(id) on delete set null,
  quiz_set_id uuid references public.quiz_sets(id) on delete set null
);

alter table public.quiz_sets
  add column if not exists minutes integer not null default 20,
  add column if not exists questions jsonb not null default '[]'::jsonb,
  add column if not exists is_active boolean not null default true,
  add column if not exists created_by uuid references auth.users(id) on delete set null,
  add column if not exists created_at timestamptz not null default now();

alter table public.student_scores
  add column if not exists responses jsonb not null default '[]'::jsonb,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists student_id uuid references auth.users(id) on delete set null,
  add column if not exists quiz_set_id uuid references public.quiz_sets(id) on delete set null;

alter table public.quiz_sets enable row level security;
alter table public.student_scores enable row level security;

revoke all on table public.quiz_sets from anon, authenticated;
grant select, insert, update, delete on table public.quiz_sets to authenticated;

drop policy if exists "JLaw students and admins read quiz sets" on public.quiz_sets;
create policy "JLaw students and admins read quiz sets"
on public.quiz_sets for select to authenticated
using (is_active = true or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "JLaw admins manage quiz sets" on public.quiz_sets;
create policy "JLaw admins manage quiz sets"
on public.quiz_sets for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

revoke all on table public.student_scores from anon, authenticated;
grant insert, select on table public.student_scores to authenticated;

drop policy if exists "JLaw anonymous score submissions" on public.student_scores;
drop policy if exists "JLaw admins can view submissions" on public.student_scores;
drop policy if exists "JLaw students submit their own scores" on public.student_scores;
create policy "JLaw students submit their own scores"
on public.student_scores for insert to authenticated
with check (
  auth.uid() is not null
  and student_id = auth.uid()
  and char_length(student_name) > 0
  and score >= 0
  and total_questions > 0
  and score <= total_questions
  and time_taken_seconds >= 0
  and jsonb_typeof(responses) = 'array'
);

drop policy if exists "JLaw students and admins read scores" on public.student_scores;
create policy "JLaw students and admins read scores"
on public.student_scores for select to authenticated
using (
  student_id = auth.uid()
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

do $$
declare score_sequence regclass := pg_get_serial_sequence('public.student_scores', 'id');
begin
  if score_sequence is not null then
    execute format('grant usage, select on sequence %s to authenticated', score_sequence);
  end if;
end
$$;

-- Student profile rows are created automatically after Supabase Auth signup.
-- Access roles remain in auth.users.app_metadata, never in editable profile data.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
revoke all on table public.profiles from anon, authenticated;
grant select on table public.profiles to authenticated;
grant update (full_name) on table public.profiles to authenticated;

drop policy if exists "JLaw users read own profile" on public.profiles;
create policy "JLaw users read own profile"
on public.profiles for select to authenticated
using (id = auth.uid());

drop policy if exists "JLaw users update own profile" on public.profiles;
create policy "JLaw users update own profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create or replace function public.handle_jlaw_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    coalesce(nullif(pg_catalog.btrim(new.raw_user_meta_data ->> 'full_name'), ''), '')
  )
  on conflict (id) do update
    set full_name = excluded.full_name,
        updated_at = now();
  return new;
end;
$$;

revoke all on function public.handle_jlaw_new_user() from public, anon, authenticated;
drop trigger if exists on_jlaw_auth_user_created on auth.users;
create trigger on_jlaw_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_jlaw_new_user();

-- Backfill accounts that already existed before this profile trigger was added.
insert into public.profiles (id, full_name)
select u.id,
       coalesce(nullif(pg_catalog.btrim(u.raw_user_meta_data ->> 'full_name'), ''), '')
from auth.users as u
on conflict (id) do nothing;
